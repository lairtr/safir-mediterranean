// Generates src/app/shared/journey-map.data.ts: SVG paths for the
// "Istanbul ⇄ Long Island City" map (coastlines from Natural Earth via
// world-atlas, public domain). Re-run only if you change the framing:
//   npm run build-map
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoDistance, geoInterpolate, geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

const W = 1200;
const H = 520;
// [longitude, latitude]
const LIC = [-73.953, 40.744]; // 47-31 Vernon Blvd, Long Island City
const IST = [28.979, 41.015]; // Istanbul (Sultanahmet)
// Map framing: eastern North America → Atlantic → Europe / Anatolia
const BOUNDS = { west: -98, east: 48, south: 18, north: 66 };

const topo = JSON.parse(await readFile(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

const frame = {
  type: 'MultiPoint',
  coordinates: [
    [BOUNDS.west, BOUNDS.south],
    [BOUNDS.east, BOUNDS.south],
    [BOUNDS.west, BOUNDS.north],
    [BOUNDS.east, BOUNDS.north],
    [(BOUNDS.west + BOUNDS.east) / 2, BOUNDS.north],
  ],
};
const projection = geoNaturalEarth1()
  .rotate([-(BOUNDS.west + BOUNDS.east) / 2, 0])
  .fitExtent([[0, 0], [W, H]], frame)
  .clipExtent([[0, 0], [W, H]]);
const path = geoPath(projection).digits(1);

// Great-circle flight path, sampled and projected
const interp = geoInterpolate(LIC, IST);
const pts = Array.from({ length: 97 }, (_, i) => projection(interp(i / 96)));
const arc = 'M' + pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L');

const [licX, licY] = projection(LIC);
const [istX, istY] = projection(IST);
const miles = Math.round((geoDistance(LIC, IST) * 3958.8) / 10) * 10;

const out = `// Generated by scripts/build-map.mjs — do not edit by hand.
// Coastlines: Natural Earth (public domain) via world-atlas.
export const JOURNEY_MAP = {
  width: ${W},
  height: ${H},
  land: '${path(land)}',
  arc: '${arc}',
  lic: { x: ${licX.toFixed(1)}, y: ${licY.toFixed(1)} },
  istanbul: { x: ${istX.toFixed(1)}, y: ${istY.toFixed(1)} },
  /** Great-circle distance, rounded to 10 miles */
  miles: ${miles},
} as const;
`;
await writeFile(join(ROOT, 'src/app/shared/journey-map.data.ts'), out);
console.log(`✓ journey-map.data.ts (${(out.length / 1024).toFixed(1)} KB), distance ≈ ${miles} mi`);
console.log(`  LIC at ${licX.toFixed(0)},${licY.toFixed(0)}  Istanbul at ${istX.toFixed(0)},${istY.toFixed(0)}`);
